/**
 * The pinned A2UI v1.0 spec schemas (`../a2ui-spec`, copied by `sync-a2ui-spec.mjs`) are shipped as
 * values the sdk reads — the sdk runs in the browser too, so it cannot read files.
 * This script embeds them into `src/a2ui/spec.generated.ts`; build, typecheck and test run it
 * first. Generated, never edited.
 */
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const spec = resolve(here, '../../a2ui-spec');
const target = resolve(here, '../src/a2ui/spec.generated.ts');

const read = path => JSON.parse(readFileSync(resolve(spec, path), 'utf8'));
const json = name => read(`specification/v1_0/json/${name}.json`);
const upstream = read('UPSTREAM.json');
const basicCatalog = read('catalogs/basic/v1/catalog.json');

/** Each embedded value: its name, its file, and what the sdk reads it for. */
const values = [
  [
    'COMMON_TYPES_SCHEMA',
    json('common_types'),
    '`common_types.json`: the definitions a catalog and the messages reference.',
  ],
  [
    'AGENT_TO_RENDERER_SCHEMA',
    json('agent_to_renderer'),
    '`agent_to_renderer.json`: one message an agent sends a renderer, which the schema-form check compiles.',
  ],
  [
    'RENDERER_TO_AGENT_SCHEMA',
    json('renderer_to_agent'),
    '`renderer_to_agent.json`: one message a renderer sends an agent, which the schema-form check compiles.',
  ],
  [
    'AGENT_CAPABILITIES_SCHEMA',
    json('agent_capabilities'),
    "`agent_capabilities.json`: what an agent's card declares under the A2UI extension's params.",
  ],
  [
    'RENDERER_CAPABILITIES_SCHEMA',
    json('renderer_capabilities'),
    '`renderer_capabilities.json`: what a renderer attaches as `a2uiRendererCapabilities`.',
  ],
  [
    'RENDERER_DATA_MODEL_SCHEMA',
    json('renderer_data_model'),
    '`renderer_data_model.json`: what a renderer attaches as `a2uiRendererDataModel`.',
  ],
  [
    'CATALOG_DEFINITION_SCHEMA',
    json('catalog_definition'),
    '`catalog_definition.json`: what a catalog document is, which the catalog gate validates against.',
  ],
  [
    'BASIC_CATALOG_SCHEMA',
    basicCatalog,
    "The v1 basic catalog's `catalog.json`: the options its components declare (the credential bar).",
  ],
];

const body = [
  `// GENERATED by scripts/embed-spec.mjs from a2ui-spec/. Do not edit.`,
  `/** The upstream commit the pinned spec was copied from. */`,
  `export const A2UI_SPEC_COMMIT = ${JSON.stringify(upstream.commit)};`,
  `/** The id of the standard basic catalog, as its pinned \`catalog.json\` declares it. */`,
  `export const BASIC_CATALOG_ID = ${JSON.stringify(basicCatalog.catalogId)};`,
  ...values.flatMap(([name, value, what]) => [
    `/** A2UI v1.0 ${what} Verbatim. */`,
    `export const ${name}: Record<string, unknown> = ${JSON.stringify(value)};`,
  ]),
  '',
].join('\n');

mkdirSync(dirname(target), {recursive: true});
writeFileSync(target, body);
