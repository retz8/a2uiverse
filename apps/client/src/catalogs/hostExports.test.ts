/**
 * The sdk's `HOST_EXPORTS` held to what the client lends: each lent module's export names, as the
 * client resolves the module, are the list's, sorted. Stellify refuses at pack a named import the
 * list does not hold. After moving a lent package, write the list again from these same modules:
 * `pnpm --filter @a2uiverse/client write:host-exports`, which runs this file with
 * `UPDATE_HOST_EXPORTS=1` and rebuilds the sdk.
 */
import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {expect, test} from 'vitest';
import {HOST_EXPORTS, HOST_INTERFACE_VERSION, HOST_SPECIFIERS} from '@a2uiverse/sdk';
import {HOST_MODULES} from './host';

const updating = process.env.UPDATE_HOST_EXPORTS === '1';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');
const target = resolve(root, 'packages/sdk/js/src/hostExports.generated.ts');

const lent = (specifier: (typeof HOST_SPECIFIERS)[number]): string[] =>
  Object.keys(HOST_MODULES[specifier] as object).sort();

test.skipIf(updating)(
  'the sdk lists exactly the names each module the client lends exports',
  () => {
    for (const specifier of HOST_SPECIFIERS) {
      expect(
        HOST_EXPORTS[specifier],
        `${specifier} — run pnpm --filter @a2uiverse/client write:host-exports`,
      ).toEqual(lent(specifier));
    }
  },
);

test.runIf(updating)('writes the list from the modules the client lends', () => {
  const entries = HOST_SPECIFIERS.map(
    specifier => `  ${JSON.stringify(specifier)}: ${JSON.stringify(lent(specifier))},`,
  );
  writeFileSync(
    target,
    [
      '// GENERATED by apps/client/src/catalogs/hostExports.test.ts from the modules the client lends. Do not edit.',
      "import type {HostSpecifier} from './catalog.js';",
      '',
      `/** The export names of each module the client lends under host interface ${HOST_INTERFACE_VERSION}, sorted. */`,
      'export const HOST_EXPORTS: Readonly<Record<HostSpecifier, readonly string[]>> = {',
      ...entries,
      '};',
      '',
    ].join('\n'),
  );
  execFileSync('pnpm', ['exec', 'prettier', '--write', target], {cwd: root, stdio: 'pipe'});
});
